"""Turn a trained LoRA adapter into deployable artifacts.

export/
	<name>-<type>.gguf        llama.cpp / Ollama / LLamaSharp model file
	mmproj-<name>-f16.gguf    image encoder for llama.cpp (image projects only)
	Modelfile                 `ollama create <name> -f Modelfile`
	system_prompt.txt         the exact prompt the model was trained with
	schema.json               output JSON Schema (pass it to Ollama `format` / llama-server `response_format`)
	grammar.gbnf              GBNF grammar: data set projects always (llama-server --grammar-file); others
	                          when llama.cpp ships its Python converter (in-process bindings)
	datasets/<id>.txt         data set projects: the allowed values, one per line, for the clients' checks
	llmzempic.json            manifest for programs
	integration/              PHP, C#, Python clients and a llama-server request
	merged/                   (optional) merged Hugging Face safetensors model
"""

import json
import os
import shutil
import subprocess
import sys
import time
import urllib.request
import zipfile
from pathlib import Path

from . import vision
from .datasets import run_resolver
from .fileio import read_json, read_jsonl, write_json
from .grammar import values_grammar
from .refs import export_contract, referenced_ids
from .snippets import all_snippets, llama_server_request, pascal, snake

LLAMA_CPP_REPO = "ggml-org/llama.cpp"
OLLAMA_QUANT = {"q4_k_m": "q4_K_M", "q5_k_m": "q5_K_M"}
# llama.cpp may resize images differently than training did; leave generous room per image.
IMAGE_CONTEXT_TOKENS = 1024


def log(message):
	print(f"[{time.strftime('%H:%M:%S')}] {message}", flush=True)


def file_safe(name):
	return name.replace("/", "-").replace(":", "-")


def context_size(spec, run_dir):
	"""Pick a context window that fits the system prompt plus the longest example input."""
	rows = read_jsonl(run_dir / "train.jsonl") + read_jsonl(run_dir / "eval.jsonl")
	longest = max((len(r.get("input") or "") + len(json.dumps(r["output"])) for r in rows), default=0)
	tokens = (len(spec["system_prompt"]) + longest) // 3 + 512
	if vision.is_vision(spec):
		tokens += IMAGE_CONTEXT_TOKENS
	ctx = 4096
	while ctx < tokens and ctx < 32768:
		ctx *= 2
	return ctx


def modelfile_text(spec, gguf_file, ctx, mmproj_file=None):
	system = spec["system_prompt"].replace('"""', '" " "')
	return (
		f"# Generated by Llmzempic for \"{spec['project_name']}\" (base model: {spec['base_model']})\n"
		f"FROM ./{gguf_file}\n"
		+ (f"FROM ./{mmproj_file}\n" if mmproj_file else "")
		+ f'SYSTEM """{system}"""\n'
		"PARAMETER temperature 0\n"
		f"PARAMETER num_ctx {ctx}\n"
	)


def data_set_notes(refs):
	fields = list(dict.fromkeys(f"`{r['path'][0]}`" for r in refs))
	return f"""
## Data set values

{", ".join(fields)} only answer with values from their data sets. llama-server enforces that with
`grammar.gbnf`, loaded once at startup with `--grammar-file` (needs a 2024 or later llama-server). Don't
add a `response_format` to requests, or the server builds a slow grammar for every request. The clients
in `integration/` call llama-server. Ollama can't enforce lists this long; with it, send `schema.json` as
`format` for the JSON shape and turn on the clients' value check, which compares every value with
`datasets/` and raises an error naming any value that isn't on its list. In-process bindings (LLamaSharp, llama-cpp-python) can load `grammar.gbnf` as their grammar.
"""


def readme_text(spec, name, gguf_file, ctx, metrics, mmproj_file=None, image_tokens=None, refs=None):
	quality = ""
	if metrics:
		quality = (
			f"\nEvaluation on {metrics.get('count')} {metrics.get('eval_on', 'examples')}: "
			f"JSON valid {metrics['json_valid']:.0%}, schema valid {metrics['schema_valid']:.0%}, "
			f"exact match {metrics['exact_match']:.0%}.\n"
		)
	model_line = f"`{gguf_file}`" if gguf_file else "(no GGUF exported)"
	if mmproj_file:
		model_line += f", image encoder: `{mmproj_file}`"
	server_images = ""
	if mmproj_file:
		server_images = f" --mmproj {mmproj_file}" + (f" --image-max-tokens {image_tokens}" if image_tokens else "")
	inputs = (
		"the image base64-encoded in the user message's `images` list (text in `content` is optional)"
		if mmproj_file else "the input as a user message"
	)
	return f"""# {spec['project_name']}

Fine-tuned from `{spec['base_model']}` with Llmzempic. Model file: {model_line}.
{quality}
## Run with Ollama (Windows, Linux, macOS)

```
ollama create {name} -f Modelfile
```

Then call `POST http://localhost:11434/api/chat` with `"model": "{name}"`, {inputs},
`"format"` set to the contents of `schema.json` and `"stream": false`. The instructions
and schema are already baked into the model's system prompt. Clients: `integration/`.

## Run with llama.cpp's server

```
llama-server -m {gguf_file or 'model.gguf'}{server_images}{" --grammar-file grammar.gbnf" if refs else ""} --port 8080 -c {ctx}
```

POST `integration/llama-server-request.json` to `http://localhost:8080/v1/chat/completions`.
llama-server has no Modelfile, so always send `system_prompt.txt` as the system message.

## In-process (C# LLamaSharp, Python llama-cpp-python, ...)

Load the GGUF{" with the mmproj image encoder (llama.cpp's mtmd API)" if mmproj_file else ""}, send `system_prompt.txt` as the
system message and the input as the user message using the model's chat template, and constrain sampling to `schema.json` (or `grammar.gbnf`, when
present) with your binding's grammar / JSON-schema support. For a desktop app, shipping
llama-server next to it and calling it over localhost is often the simplest reliable option.
{data_set_notes(refs) if refs else ""}"""


def ensure_llama_cpp(opts):
	"""Locate llama.cpp's converter, downloading the latest release's Python tools if needed."""
	candidates = [opts.get("llama_cpp_dir"), os.environ.get("LLAMA_CPP_DIR"), Path(opts["tools_dir"]) / "llama.cpp"]
	for candidate in candidates:
		if candidate and (Path(candidate) / "convert_hf_to_gguf.py").exists():
			return Path(candidate)
	dest = Path(opts["tools_dir"]) / "llama.cpp"
	headers = {"User-Agent": "llmzempic", "Accept": "application/vnd.github+json"}
	request = urllib.request.Request(f"https://api.github.com/repos/{LLAMA_CPP_REPO}/releases/latest", headers=headers)
	with urllib.request.urlopen(request, timeout=30) as response:
		tag = json.load(response)["tag_name"]
	log(f"Downloading llama.cpp {tag} conversion tools (one time)")
	dest.parent.mkdir(parents=True, exist_ok=True)
	archive = dest.parent / f"llama.cpp-{tag}.zip"
	request = urllib.request.Request(f"https://github.com/{LLAMA_CPP_REPO}/archive/refs/tags/{tag}.zip", headers=headers)
	with urllib.request.urlopen(request, timeout=300) as response, open(archive, "wb") as f:
		shutil.copyfileobj(response, f)
	staging = dest.parent / f"llama.cpp-{tag}.partial"
	shutil.rmtree(staging, ignore_errors=True)
	with zipfile.ZipFile(archive) as z:
		for member in z.infolist():
			parts = Path(member.filename).parts[1:]
			if not parts or member.is_dir() or ".." in parts:
				continue
			rel = Path(*parts)
			if rel.suffix == ".py" or parts[0] in ("gguf-py", "requirements"):
				target = staging / rel
				target.parent.mkdir(parents=True, exist_ok=True)
				with z.open(member) as src, open(target, "wb") as out:
					shutil.copyfileobj(src, out)
	(staging / "VERSION").write_text(tag, encoding="utf-8")
	shutil.rmtree(dest, ignore_errors=True)
	staging.rename(dest)
	archive.unlink()
	return dest


def find_quantize(llama_dir):
	exe = "llama-quantize.exe" if os.name == "nt" else "llama-quantize"
	found = shutil.which("llama-quantize")
	if found:
		return found
	if llama_dir:
		for sub in ("", "build/bin", "build/bin/Release", "bin"):
			path = Path(llama_dir) / sub / exe
			if path.exists():
				return str(path)
	return None


def merge_adapter(spec, run_dir, merged_dir, status):
	import torch
	import transformers
	from peft import PeftModel
	from transformers import AutoModelForCausalLM, AutoTokenizer

	from .trainer import dtype_kwarg, hf_token

	status.update(stage="Loading base model for merge")
	log(f"Merging LoRA adapter into {spec['base_model']} (on CPU, 16-bit)")
	kwargs = {"token": hf_token(), "low_cpu_mem_usage": True, dtype_kwarg(transformers): torch.bfloat16}
	if vision.is_vision(spec):
		base = vision.load_model(spec["base_model"], kwargs)
		processor = vision.load_processor(run_dir / "adapter")
	else:
		base = AutoModelForCausalLM.from_pretrained(spec["base_model"], **kwargs)
		processor = AutoTokenizer.from_pretrained(str(run_dir / "adapter"))
	model = PeftModel.from_pretrained(base, str(run_dir / "adapter"))
	status.update(stage="Merging adapter")
	model = model.merge_and_unload()
	shutil.rmtree(merged_dir, ignore_errors=True)
	status.update(stage="Saving merged model")
	model.save_pretrained(str(merged_dir), safe_serialization=True, max_shard_size="5GB")
	processor.save_pretrained(str(merged_dir))
	del model, base
	log(f"Merged model saved to {merged_dir}")


def convert_gguf(llama_dir, merged_dir, out_path, outtype, mmproj=False):
	cmd = [sys.executable, str(llama_dir / "convert_hf_to_gguf.py"), str(merged_dir), "--outfile", str(out_path), "--outtype", outtype]
	if mmproj:
		cmd.append("--mmproj")
	log("Running " + " ".join(cmd))
	env = {k: v for k, v in os.environ.items() if k != "NO_LOCAL_GGUF"}
	env["TQDM_DISABLE"] = "1"  # the writer's progress bar fills export.log with carriage returns
	subprocess.run(cmd, check=True, env=env)


def write_grammar(llama_dir, export_dir):
	scripts = [Path(llama_dir) / sub / "json_schema_to_grammar.py" for sub in ("examples", "tools", "scripts")] if llama_dir else []
	script = next((p for p in scripts if p.exists()), None)
	if not script:
		return False
	result = subprocess.run(
		[sys.executable, str(script), str(export_dir / "schema.json")], capture_output=True, text=True,
	)
	if result.returncode != 0 or not result.stdout.strip():
		log(f"Could not build grammar.gbnf: {result.stderr.strip()[:500]}")
		return False
	(export_dir / "grammar.gbnf").write_text(result.stdout, encoding="utf-8")
	return True


def write_deploy_files(export_dir, spec, name, gguf_file, ctx, metrics, mmproj_file=None, image_tokens=None):
	integration = export_dir / "integration"
	integration.mkdir(parents=True, exist_ok=True)
	schema, refs = export_contract(spec["schema"], spec.get("datasets"))
	(export_dir / "schema.json").write_text(json.dumps(schema, indent=2, ensure_ascii=False), encoding="utf-8")
	(export_dir / "system_prompt.txt").write_text(spec["system_prompt"], encoding="utf-8")
	if gguf_file:
		(export_dir / "Modelfile").write_text(modelfile_text(spec, gguf_file, ctx, mmproj_file), encoding="utf-8")
	is_image = vision.is_vision(spec)
	snippets = all_snippets(name, schema, spec["system_prompt"], gguf_file, ctx, is_image, mmproj_file, image_tokens, refs)
	(integration / "client.php").write_text(snippets["php"], encoding="utf-8")
	(integration / f"{snake(name)}_client.py").write_text(snippets["python"], encoding="utf-8")
	(integration / f"{pascal(name)}Client.cs").write_text(snippets["csharp"], encoding="utf-8")
	(integration / "llama-server-request.json").write_text(
		json.dumps(
			llama_server_request(spec["system_prompt"], None if refs else schema, "" if is_image else "Text to analyze", is_image),
			indent=2, ensure_ascii=False,
		),
		encoding="utf-8",
	)
	(export_dir / "README.md").write_text(readme_text(spec, name, gguf_file, ctx, metrics, mmproj_file, image_tokens, refs), encoding="utf-8")
	write_json(export_dir / "llmzempic.json", {
		"name": name,
		"project": spec["project_name"],
		"base_model": spec["base_model"],
		"input_kind": spec.get("input_kind", "text"),
		"gguf": gguf_file,
		"mmproj": mmproj_file,
		"image_max_tokens": image_tokens,
		"context_size": ctx,
		"system_prompt": spec["system_prompt"],
		"schema": schema,
		"datasets": refs,
		"grammar": "grammar.gbnf" if refs else None,
		"inference": {"temperature": 0},
		"metrics": metrics,
		"exported": time.time(),
	})


def write_value_files(export_dir, spec, resolver):
	"""Data set projects: each data set's values for the clients' checks, and the grammar llama-server
	loads so that every data set field answers from its list."""
	values = lambda dataset_id: (value for value, _ in resolver.datasets[dataset_id].iter_rows())
	folder = export_dir / "datasets"
	folder.mkdir(parents=True, exist_ok=True)
	for dataset_id in sorted(referenced_ids(spec["schema"])):
		with open(folder / f"{dataset_id}.txt", "w", encoding="utf-8", newline="\n") as f:
			f.writelines(f"{value}\n" for value in values(dataset_id))
	(export_dir / "grammar.gbnf").write_text(values_grammar(spec["schema"], values), encoding="utf-8", newline="\n")


def run_export(run_dir, status):
	os.environ.setdefault("HF_HUB_DISABLE_PROGRESS_BARS", "1")
	export_dir = run_dir / "export"
	opts = read_json(export_dir / "options.json")
	spec = read_json(run_dir / "run.json")
	evaluation = read_json(run_dir / "eval.json", None)
	metrics = {k: v for k, v in evaluation.items() if k != "items"} if evaluation else None
	name = opts["ollama_name"]
	gguf_type = opts["gguf"]
	ctx = context_size(spec, run_dir)
	is_image = vision.is_vision(spec)
	image_tokens = vision.image_max_tokens(vision.load_processor(run_dir / "adapter")) if is_image else None
	status.update(state="running", stage="Writing deployment files", files=None, notes=[], mmproj=None)
	notes = []

	for old in export_dir.glob("*.gguf"):
		old.unlink()
	write_deploy_files(export_dir, spec, name, None, ctx, metrics)
	has_refs = bool(referenced_ids(spec["schema"]))
	if has_refs:
		status.update(stage="Writing data set lists and grammar")
		write_value_files(export_dir, spec, run_resolver(run_dir))

	gguf_file = None
	mmproj_file = None
	llama_dir = None
	merged_dir = export_dir / "merged"
	if gguf_type != "none" or opts.get("keep_merged"):
		merge_adapter(spec, run_dir, merged_dir, status)

	ollama_quantize = None
	if gguf_type != "none":
		status.update(stage="Preparing llama.cpp converter")
		llama_dir = ensure_llama_cpp(opts)
		direct = gguf_type if gguf_type in ("q8_0", "f16", "bf16") else "f16"
		gguf_file = f"{file_safe(name)}-{direct}.gguf"
		status.update(stage=f"Converting to GGUF ({direct})")
		convert_gguf(llama_dir, merged_dir, export_dir / gguf_file, direct)
		if is_image:
			# The image encoder stays f16: it's small, and quantizing it costs accuracy.
			mmproj_file = f"mmproj-{file_safe(name)}-f16.gguf"
			status.update(stage="Converting the image encoder (mmproj)")
			convert_gguf(llama_dir, merged_dir, export_dir / mmproj_file, "f16", mmproj=True)
		if direct != gguf_type:
			quantize = find_quantize(llama_dir)
			if quantize:
				final = f"{file_safe(name)}-{gguf_type}.gguf"
				status.update(stage=f"Quantizing to {gguf_type}")
				subprocess.run([quantize, str(export_dir / gguf_file), str(export_dir / final), gguf_type.upper()], check=True)
				(export_dir / gguf_file).unlink()
				gguf_file = final
			else:
				ollama_quantize = OLLAMA_QUANT[gguf_type]
				notes.append(
					f"llama-quantize was not found, so the GGUF is f16. Ollama will quantize it to {gguf_type} "
					f"with: ollama create {name} --quantize {ollama_quantize} -f Modelfile"
				)
		write_deploy_files(export_dir, spec, name, gguf_file, ctx, metrics, mmproj_file, image_tokens)
		if not has_refs:
			status.update(stage="Building grammar")
			if not write_grammar(llama_dir, export_dir):
				log("grammar.gbnf not generated (no Python schema converter in this llama.cpp); Ollama and llama-server use schema.json directly.")

	if merged_dir.exists() and not opts.get("keep_merged"):
		shutil.rmtree(merged_dir, ignore_errors=True)

	if opts.get("ollama") and gguf_file:
		ollama = shutil.which("ollama")
		if not ollama:
			notes.append("Ollama is not installed or not on PATH; register the model later with the Modelfile.")
		else:
			status.update(stage=f"Registering '{name}' with Ollama")
			cmd = [ollama, "create", name, "-f", "Modelfile"]
			if ollama_quantize:
				cmd += ["--quantize", ollama_quantize]
			log("Running " + " ".join(cmd))
			subprocess.run(cmd, check=True, cwd=str(export_dir))
			notes.append(f"Registered with Ollama as '{name}'.")

	for note in notes:
		log(note)
	status.update(state="completed", stage="Completed", gguf=gguf_file, mmproj=mmproj_file, notes=notes, export_dir=str(export_dir))
